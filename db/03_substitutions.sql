   'Тот же профиль плюс CI/CD и SQL. Запас 543 ЧЧ.'),

  -- ---- Поддержка BigData: спроса сейчас нет, правило на будущее -----
  ('Специалист поддержки BigData', 'Аналитик Big Data', 'Middle', 1.00,
   'Общий стек Python/SQL/Hadoop/Spark. В датасете v1 спрос нулевой — правило про запас.')
) AS v(required, covering, min_grade, efficiency, rationale)
