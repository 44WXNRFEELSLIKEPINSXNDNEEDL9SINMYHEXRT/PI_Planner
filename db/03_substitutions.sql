   'Управленец с отраслевой приставкой; полная ставка — 525.71 ЧЧ за квартал, в плане не загружен.'),

  ('Руководитель проекта', 'Аналитик', 'Senior', 1.00,
   'Сеньор-аналитики ведут требования и сроки: ENG-428 «бизнес-анализ, сбор требований, ТЗ», '
   'ENG-404 «BPMN, UML, Confluence». Запас роли 701 ЧЧ. Только Senior — джун инициативу не потянет.'),

  ('Руководитель проекта', 'Архитектор решений', 'Senior', 1.00,
   'ENG-418, TOGAF: ведёт техническую часть инициативы. Запас 151 ЧЧ — резерв, а не основной носитель.'),

  -- ---- Специалист поддержки: 84 ЧЧ, 10 задач по ~10 ЧЧ -------------
