SELECT req.role_id, cov.role_id, v.min_grade, v.efficiency, 'rejected', v.rationale
FROM (VALUES
  -- ---- Руководитель проекта: 449 ЧЧ, 25 задач, в штате роли нет -----
  ('Руководитель проекта', 'Руководитель BigData', 'Senior', 1.00,
